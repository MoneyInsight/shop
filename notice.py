def kind_of(p):
    name = p.get("name", "")
    for kind, words in NAME_HINT:
        if any(w in name for w in words.split()):
            return kind
    return CAT_TO_KIND.get(p.get("category"), "기타 재화")


def rows(p, biz):
    """(항목, 값) 목록. p['notice'] (도매처 고시 값 dict) 가 있으면 우선 사용"""
    kind = kind_of(p)
    given = p.get("notice") or {}
    out = [("고시 품목", kind), ("상품명", p.get("name", "")), ("브랜드", p.get("brand") or REF), ("제조자 / 수입자", p.get("maker") or REF), ("제조국", given.get("제조국") or REF)]
    for item in ITEMS.get(kind, ITEMS["기타 재화"]):
        if item == "KC 인증 필 유무":
            out.append(("KC 인증", p.get("kc") or ("해당 시 " + REF)))
        else:
            out.append((item, given.get(item) or REF))
    if kind in KC_KINDS and not any(k == "KC 인증" for k, _ in out):
        out.append(("KC 인증", p.get("kc") or ("해당 시 " + REF)))
    out += [("품질보증 기준", "관련 법 및 소비자분쟁해결기준에 따름"), ("A/S 책임자와 전화번호", f'{biz["company"]} {biz["phone"]}')]
    return out


def needs_kc(p):
    return kind_of(p) in KC_KINDS
